		text(&b, colX+18, 337.5, 14.5, "#245bdb", "500", "💡  "+callout, "")

		// Two-column architecture notes.
		rect(&b, colX, 384, 356, 136, 10, `fill="#fafbfc" stroke="#e5e8ef" stroke-width="1"`)
