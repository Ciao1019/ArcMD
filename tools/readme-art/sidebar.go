	fmt.Fprintf(&css, `@keyframes cap0{0%%,%s{opacity:1}%s,%s{opacity:.38}%s,100%%{opacity:1}}.cap0{animation-name:cap0}`+"\n", p(5.1), p(5.6), p(14.1), p(14.9))
