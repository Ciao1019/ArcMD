func drawSideList(b *bytes.Buffer, pal spacePalette, items []sideItem, newDoc string) {
	y := 154.0
	drewSep := false
	for _, it := range items {
		if !it.pinned && !drewSep {
			fmt.Fprintf(b, `<path d="M18 %.1fh194" stroke="%s" stroke-opacity=".14" stroke-width="1" stroke-linecap="round"/>`+"\n", y+9, pal.ink)
			y += 19
			drewSep = true
		}
		if it.active {
			rect(b, 8, y, 214, 36, 10, `fill="#fff" fill-opacity=".76" stroke="#000" stroke-opacity=".045"`)
		}
		if it.folder {
			fmt.Fprintf(b, `<use href="#folder-%s" x="18" y="%.1f"/>`+"\n", pal.id, y+10)
			text(b, 44, y+23.5, 14, pal.ink, "500", it.title, "")
		} else {
			drawDocIcon(b, 18, y+10, 16, it.glyph, it.color)
			w := "400"
			if it.active {
				w = "500"
			}
			text(b, 44, y+23.5, 14, pal.ink, w, it.title, "")
		}
		y += 40
	}
	y += 6
	rect(b, 10, y, 210, 36, 10, fmt.Sprintf(`fill="#fff" fill-opacity=".12" stroke="%s" stroke-opacity=".24" stroke-width="1" stroke-dasharray="4 3.5"`, pal.ink))
	text(b, 115, y+23, 13, pal.muted, "500", "+  "+newDoc, `text-anchor="middle"`)
}
