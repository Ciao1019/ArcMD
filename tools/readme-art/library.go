package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

const libraryDuration = 16.0

func buildLibrary() error {
	for _, zh := range []bool{true, false} {
		if err := buildLibraryLocale(zh); err != nil {
			return err
		}
	}
	return nil
}

func buildLibraryLocale(zh bool) error {
	code := "en"
	if zh {
		code = "zh-CN"
	}
	p := func(t float64) string { return pct(t, libraryDuration) }

	var (
		aria, tab1, tab2, tab3                     string
		s2Name, s3Name                             string
		c1                                         itemsCard = itemsCard{}
		c2                                         itemsCard = itemsCard{}
		c3                                         itemsCard = itemsCard{}
		p1Title, p1Sub, p1Body, rTitle, rSub, rQuo string
		captions                                   []string
		capX                                       []float64
	)
	if zh {
		aria = "ArcMD 资料库动图：点击左下角资料库图标，展开 Personal、工作、阅读三张主题空间卡片，点击阅读空间里的读书笔记即可直接跳过去打开。"
		tab1, tab2, tab3 = "空间", "插件", "最近删除"
		s2Name, s3Name = "工作", "阅读"
		c1 = itemsCard{"Personal", "✦", "#b03e74", "#fde7f0", "#f7e2f7", [3]string{"留一点空白", "书写手记", "今日笔记"}}
		c2 = itemsCard{"工作", "◈", "#2864b8", "#e1f0fc", "#e6e8fc", [3]string{"架构设计", "性能基准", "产品路线图"}}
		c3 = itemsCard{"阅读", "📚", "#c25420", "#fde9d8", "#fbf2d4", [3]string{"读书笔记", "树语摘录", "年度书单"}}
		p1Title, p1Sub = "留一点空白", "从左下角打开资料库，所有空间的文件夹与页面都在眼前。"
		p1Body = "每个空间使用各自的主题色绘制卡片，插件与 30 天「最近删除」也集中在这里。"
		rTitle, rSub = "读书笔记", "点击任意空间卡片里的文档，即刻切入对应空间并恢复阅读进度。"
		rQuo = "“好的空间感，是让每件事都待在它该在的地方。”"
		captions = []string{"点击左下角资料库（⇧⌘L）", "三张主题空间卡片一览无余", "点任意文档，直接切入打开"}
		capX = []float64{136, 488, 852}
	} else {
		aria = "ArcMD Library animation: click the Library icon to reveal themed cards for Personal, Work, and Reading spaces, then click a page in Reading to jump straight into it."
		tab1, tab2, tab3 = "Spaces", "Plugins", "Recently Deleted"
		s2Name, s3Name = "Work", "Reading"
		c1 = itemsCard{"Personal", "✦", "#b03e74", "#fde7f0", "#f7e2f7", [3]string{"Room to think", "Writing flow", "Today's note"}}
		c2 = itemsCard{"Work", "◈", "#2864b8", "#e1f0fc", "#e6e8fc", [3]string{"Architecture", "Benchmarks", "Roadmap"}}
		c3 = itemsCard{"Reading", "📚", "#c25420", "#fde9d8", "#fbf2d4", [3]string{"Reading notes", "The Overstory", "Book list"}}
		p1Title, p1Sub = "Room to think", "Open the Library from the corner to see every space side by side."
		p1Body = "Each space is painted in its own theme colors, with Plugins and 30-day Trash one tab away."
		rTitle, rSub = "Reading notes", "Pick any document card to jump straight into its space."
		rQuo = "“A calm workspace gives every project a room of its own.”"
		captions = []string{"Open the Library (⇧⌘L)", "All spaces painted in theme", "Click any page to jump in"}
		capX = []float64{142, 488, 856}
	}

	var b, css bytes.Buffer
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 820" width="1280" height="820" role="img" aria-label="%s">`+"\n", esc(aria))
	b.WriteString("<!-- Generated by go run ./tools/readme-art -->\n")
	css.WriteString(baseFontCSS())
	fmt.Fprintf(&css, `.l{animation-duration:%.0fs;animation-iteration-count:infinite;animation-fill-mode:both;animation-timing-function:cubic-bezier(.65,0,.35,1)}`+"\n", libraryDuration)

	// 0..2.2s: Personal space -> click Library icon at (25, 728)
	// 2.2..8.6s: Library drawer open (width 760) showing 3 cards; pointer hovers Reading card row 0 & clicks at 8.0s
	// 8.6..14.4s: Drawer closes -> window is now in Amber Reading space showing Reading notes.md
	// 14.4..16.0s: Reset to Personal
	fmt.Fprintf(&css, `@keyframes drawer{0%%,%s{transform:translateX(-780px)}%s,%s{transform:translateX(0)}%s,100%%{transform:translateX(-780px)}}.drawer{animation-name:drawer}`+"\n", p(2.1), p(2.9), p(8.3), p(9.1))
	fmt.Fprintf(&css, `@keyframes pagePush{0%%,%s{transform:translateX(0)}%s,%s{transform:translateX(536px)}%s,100%%{transform:translateX(0)}}.pagePush{animation-name:pagePush}`+"\n", p(2.1), p(2.9), p(8.3), p(9.1))
	fmt.Fprintf(&css, `@keyframes shellAmb{0%%,%s{opacity:0}%s,%s{opacity:1}%s,100%%{opacity:0}}.shellAmb{animation-name:shellAmb}`+"\n", p(8.1), p(8.9), p(14.4), p(15.3))
	fmt.Fprintf(&css, `@keyframes showAmbDoc{0%%,%s{opacity:0}%s,%s{opacity:1}%s,100%%{opacity:0}}.showAmbDoc{animation-name:showAmbDoc}`+"\n", p(8.1), p(8.8), p(14.4), p(15.3))
	fmt.Fprintf(&css, `@keyframes hideRoseDoc{0%%,%s{opacity:1}%s,%s{opacity:0}%s,100%%{opacity:1}}.hideRoseDoc{animation-name:hideRoseDoc}`+"\n", p(8.0), p(8.7), p(14.5), p(15.3))
	fmt.Fprintf(&css, `@keyframes rowHover{0%%,%s{opacity:0}%s,%s{opacity:1}%s,100%%{opacity:0}}.rowHover{animation-name:rowHover}`+"\n", p(5.6), p(6.1), p(8.2), p(8.6))
	fmt.Fprintf(&css, `@keyframes libPtr{0%%{opacity:0;transform:translate(420px,520px)}%s{opacity:1;transform:translate(420px,520px)}%s,%s{opacity:1;transform:translate(26px,728px)}%s{opacity:1;transform:translate(410px,320px)}%s,%s{opacity:1;transform:translate(612px,254px)}%s,100%%{opacity:0;transform:translate(660px,300px)}}.libPtr{animation-name:libPtr}`+"\n",
		p(0.5), p(1.7), p(2.3), p(4.6), p(6.2), p(8.2), p(9.2))
	fmt.Fprintf(&css, `@keyframes cap0{0%%,%s{opacity:1}%s,%s{opacity:.38}%s,100%%{opacity:1}}.cap0{animation-name:cap0}`+"\n", p(2.3), p(2.8), p(14.6), p(15.3))
	fmt.Fprintf(&css, `@keyframes cap1{0%%,%s{opacity:.38}%s,%s{opacity:1}%s,100%%{opacity:.38}}.cap1{animation-name:cap1}`+"\n", p(2.3), p(2.8), p(7.9), p(8.4))
	fmt.Fprintf(&css, `@keyframes cap2{0%%,%s{opacity:.38}%s,%s{opacity:1}%s,100%%{opacity:.38}}.cap2{animation-name:cap2}`+"\n", p(7.9), p(8.4), p(14.5), p(15.2))

	css.WriteString(`@media(prefers-reduced-motion:reduce){.l{animation:none!important}.libPtr,.shellAmb,.showAmbDoc{display:none}.drawer{transform:translateX(0)!important}.pagePush{transform:translateX(536px)!important}.rowHover,.cap0,.cap1,.cap2{opacity:1!important}}` + "\n")
	fmt.Fprintf(&b, "<style>\n%s</style>\n", css.String())

	extraDefs := fmt.Sprintf(`<linearGradient id="libCard1" x1="0" y1="0" x2="0" y2="1"><stop stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>
<linearGradient id="libCard2" x1="0" y1="0" x2="0" y2="1"><stop stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>
<linearGradient id="libCard3" x1="0" y1="0" x2="0" y2="1"><stop stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>
<linearGradient id="covSunLib" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#ffb085"/><stop offset="1" stop-color="#fff0b8"/></linearGradient>
`, c1.top, c1.bot, c2.top, c2.bot, c3.top, c3.bot)

	writeCommonDefs(&b, extraDefs)
	writeStageBackdrop(&b, true)

	roseSpec := defaultRoseSpec(zh, p1Title, "🌿", "#2b8a3e", map[bool]string{true: "186 字", false: "142 words"}[zh])
	ambSpec := shellSpec{
		pal: palAmber, spaceIcon: "📚", spaceName: s3Name,
		addressDoc: s3Name + " / " + rTitle + ".md", docGlyph: "📚", docColor: "#d9480f",
		wordCount: map[bool]string{true: "318 字", false: "236 words"}[zh], goalRatio: 0.85,
		newDocText: map[bool]string{true: "新建文档", false: "New document"}[zh],
		activeFav:  -1, activeSw: 2, favs: defaultFavs(zh),
		items: []sideItem{
			{folder: true, title: map[bool]string{true: "书架", false: "Shelf"}[zh], pinned: true},
			{glyph: "📚", color: "#d9480f", title: rTitle, active: true, pinned: true},
			{glyph: "树", color: "#2b8a3e", title: c3.docs[1]},
			{glyph: "书", color: "#ae3ec9", title: c3.docs[2]},
		},
	}
	if !zh {
		ambSpec.items[2].glyph = "O"
		ambSpec.items[3].glyph = "B"
	}

	b.WriteString(`<g clip-path="url(#win)">` + "\n")
	b.WriteString(`<g class="l hideRoseDoc">` + "\n")
	rect(&b, 0, 0, 1240, 760, 0, `fill="url(#sh-rose)"`)
	writeToolbarChrome(&b, roseSpec, false)
	writeSidebarContent(&b, roseSpec, false)
	b.WriteString("</g>\n")

	b.WriteString(`<g class="l shellAmb">` + "\n")
	rect(&b, 0, 0, 1240, 760, 0, `fill="url(#sh-amber)"`)
	writeToolbarChrome(&b, ambSpec, false)
	writeSidebarContent(&b, ambSpec, false)
	b.WriteString("</g>\n")
	voidUse := s2Name
	_ = voidUse

	// Document card (pushed right while Library drawer is open).
	b.WriteString(`<g class="l pagePush">` + "\n")
	rect(&b, 230, 46, 1002, 706, 10, `fill="#fff" stroke="#000" stroke-opacity=".06"`)
	b.WriteString(`<g clip-path="url(#card)">` + "\n")
	b.WriteString(`<g class="l hideRoseDoc">` + "\n")
	text(&b, 310, 134, 33, "#1f2329", "600", p1Title, "")
	text(&b, 310, 176, 16, "#646a73", "400", p1Sub, "")
	rect(&b, 310, 208, 620, 54, 9, `fill="#eff5ff" stroke="#cfe0fc" stroke-width="1"`)
	text(&b, 328, 240.5, 15, "#245bdb", "500", "✦  "+p1Body, "")
	b.WriteString("</g>\n")

	b.WriteString(`<g class="l showAmbDoc">` + "\n")
	rect(&b, 230, 46, 1002, 118, 0, `fill="url(#covSunLib)"`)
	text(&b, 310, 180, 40, "#1f2329", "400", "📚", "")
	text(&b, 310, 236, 33, "#1f2329", "600", rTitle, "")
	text(&b, 310, 274, 16, "#646a73", "400", rSub, "")
	rect(&b, 310, 308, 3, 44, 1.5, `fill="#e0a96d"`)
	text(&b, 328, 336, 16.5, "#495057", "400", rQuo, "")
	b.WriteString("</g>\n")
	b.WriteString("</g></g>\n") // card & pagePush

	// Sliding Library Drawer (x=0..754, y=46..752) with 3 themed Space Cards!
	b.WriteString(`<g class="l drawer">` + "\n")
	rect(&b, 10, 46, 744, 706, 14, `fill="#fcfbfd" fill-opacity=".95" stroke="#000" stroke-opacity=".08" stroke-width="1"`)
	// Segmented Library Tabs: Spaces | Plugins | Recently Deleted
	rect(&b, 26, 62, 276, 32, 9, `fill="#efecf3"`)
	rect(&b, 29, 65, 78, 26, 7, `fill="#fff" stroke="#ded9e6" stroke-width=".8"`)
	text(&b, 68, 82.5, 12.5, "#1f2329", "600", tab1, `text-anchor="middle"`)
	text(&b, 148, 82.5, 12.5, "#646a73", "500", tab2, `text-anchor="middle"`)
	text(&b, 244, 82.5, 12.5, "#646a73", "500", tab3, `text-anchor="middle"`)

	cards := []struct {
		c    itemsCard
		grad string
		fID  string
	}{
		{c1, "libCard1", "rose"},
		{c2, "libCard2", "sky"},
		{c3, "libCard3", "amber"},
	}
	for idx, entry := range cards {
		cx := 26.0 + float64(idx)*240
		rect(&b, cx, 112, 226, 616, 14, fmt.Sprintf(`fill="url(#%s)" stroke="#000" stroke-opacity=".06"`, entry.grad))
		text(&b, cx+18, 146, 16, entry.c.accent, "700", entry.c.icon, "")
		text(&b, cx+42, 146, 15, "#2b2733", "600", entry.c.name, "")
		fmt.Fprintf(&b, `<path d="M%.1f 164h190" stroke="#000" stroke-opacity=".08"/>`+"\n", cx+18)

		// 1 folder + 3 doc rows inside each Space card.
		fmt.Fprintf(&b, `<use href="#folder-%s" x="%.1f" y="182"/>`+"\n", entry.fID, cx+18)
		folderLabel := map[int]string{0: map[bool]string{true: "日记", false: "Journal"}[zh], 1: map[bool]string{true: "规范", false: "Specs"}[zh], 2: map[bool]string{true: "书架", false: "Shelf"}[zh]}[idx]
		text(&b, cx+42, 195, 13.5, "#2f2c38", "500", folderLabel, "")

		docColors := [3]string{"#2b8a3e", "#7048e8", "#0c8599"}
		for j, dName := range entry.c.docs {
			ry := 222.0 + float64(j)*44
			if idx == 2 && j == 0 {
				rect(&b, cx+10, ry, 206, 36, 9, `fill="#fff" fill-opacity=".86" stroke="#c25420" stroke-opacity=".28" class="l rowHover"`)
			} else {
				rect(&b, cx+10, ry, 206, 36, 9, `fill="#fff" fill-opacity=".42"`)
			}
			r0 := []rune(dName)
			drawDocIcon(&b, cx+18, ry+10, 16, string(r0[0]), docColors[j])
			text(&b, cx+42, ry+23, 13.5, "#1f2329", "500", dName+".md", "")
		}
	}
	b.WriteString("</g>\n") // drawer

	b.WriteString(`<g class="l libPtr"><use href="#cursor"/></g>` + "\n")
	b.WriteString("</g></g>\n")

	writeCaptionBar(&b, "l", captions, capX)
	b.WriteString("</g></svg>\n")

	out := filepath.Join("docs/images/readme", "library-"+code+".svg")
	if err := os.WriteFile(out, b.Bytes(), 0644); err != nil {
		return err
	}
	fmt.Printf("%s (%d bytes)\n", out, b.Len())
	return nil
}

type itemsCard struct {
	name   string
	icon   string
	accent string
	top    string
	bot    string
	docs   [3]string
}
